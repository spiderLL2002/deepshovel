// Generate the TypeScript and Python modules for the cross-language contract.
//
//   node scripts/generate-shared-contract.mjs          write both modules
//   node scripts/generate-shared-contract.mjs --check  fail if either is stale
//
// contracts/shared-contract.json is the only place these values are edited.
