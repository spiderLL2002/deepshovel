function lookup(source, dotted) {
  let value = source;
  for (const part of dotted.split(".")) {
    if (value === null || typeof value !== "object" || !Object.hasOwn(value, part)) {
      throw new Error(`shared contract is missing ${dotted}`);
    }
    value = value[part];
  }
  return value;
}

function scalar(value, dotted) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  throw new Error(`${dotted} must be a string, finite number or string array`);
}

function stringArray(value, dotted) {
  if (!Array.isArray(value) || value.length === 0 || value.some((item) => typeof item !== "string")
    || new Set(value).size !== value.length) {
    throw new Error(`${dotted} must be a non-empty array of unique strings`);
  }
  return value.map((item) => JSON.stringify(item));
}

const HEADER = "GENERATED by scripts/generate-shared-contract.mjs from contracts/shared-contract.json. Do not edit.";

export function renderSharedContract(source = JSON.parse(fs.readFileSync(SOURCE_PATH, "utf8"))) {
  const ts = [`// ${HEADER}`, ""];
  const py = [
    '"""Cross-language contract constants. GENERATED: do not edit.',
    "",
    "Source: contracts/shared-contract.json. Regenerate with",
    "``node scripts/generate-shared-contract.mjs``.",
    '"""',
    "",
    "from __future__ import annotations",
    "",
    "from typing import Final, Literal",
    "",
  ];
  for (const [dotted, tsName, pyName, literalAlias] of FIELDS) {
    const value = lookup(source, dotted);
    if (Array.isArray(value)) {
      const items = stringArray(value, dotted);
      ts.push(`export const ${tsName} = [${items.join(", ")}] as const;`);
      py.push(`${pyName}: Final = (`, ...items.map((item) => `    ${item},`), ")");
      if (literalAlias) py.push(`${literalAlias} = Literal[`, ...items.map((item) => `    ${item},`), "]");
    } else {
      const rendered = scalar(value, dotted);
      ts.push(`export const ${tsName} = ${rendered}${typeof value === "string" ? " as const" : ""};`);
      py.push(`${pyName}: Final = ${rendered}`);
    }
  }
  return { ts: `${ts.join("\n")}\n`, py: `${py.join("\n")}\n` };
}

function main(argv) {
  const { ts, py } = renderSharedContract();
  const outputs = [[TS_PATH, ts], [PY_PATH, py]];
  if (argv.includes("--check")) {
    const stale = outputs.filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text);
    if (stale.length) {
      console.error(`Stale generated contract module(s): ${stale.map(([file]) => path.relative(root, file)).join(", ")}`);
      console.error("Run: node scripts/generate-shared-contract.mjs");
      process.exit(1);
    }
    return;
  }
  for (const [file, text] of outputs) fs.writeFileSync(file, text);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
